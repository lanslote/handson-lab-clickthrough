import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { browserServers, MemoryStore, adminKey } from './helpers.js';

test('confirmed archive and restore have separate views, retain students and never silently archive on network failure', { timeout: 90000 }, async t => {
  const servers = await browserServers(new MemoryStore()); t.after(() => servers.close());
  const teacherSession = await servers.create(), studentSession = await servers.joinStudent(teacherSession);
  await servers.gate(teacherSession, '3-1', true); await servers.enter(studentSession, '3-1');
  await servers.progress(studentSession, '3-1', 'intro', 0);
  const browser = await chromium.launch({ channel: 'msedge', headless: true }); t.after(() => browser.close());
  const teacherContext = await browser.newContext(), studentContext = await browser.newContext();
  await studentContext.addInitScript(({ origin, session }) => {
    if (location.protocol === 'http:') localStorage.setItem(`lab3.session:${origin}:student`, JSON.stringify(session));
  }, { origin: servers.apiOrigin, session: studentSession });
  const teacher = await teacherContext.newPage(), student = await studentContext.newPage(), errors = [];
  for (const page of [teacher, student]) page.on('pageerror', error => errors.push(error.message));
  await teacher.goto(servers.origin + '/lab3/instructor.html');
  await teacher.locator('#admin-login [name=admin]').fill(adminKey); await teacher.locator('#admin-login button').click();
  await expect(teacher.locator('#admin-home')).toBeVisible();
  const card = teacher.locator('#classrooms-list article').filter({ has: teacher.locator(`[data-manage="${teacherSession.classroomId}"]`) });
  await card.locator('summary').click();
  const cancelled = teacher.waitForEvent('dialog').then(dialog => {
    assert.ok(dialog.message().includes('함께하는 실습')); assert.ok(dialog.message().includes('기록은 유지'));
    return dialog.dismiss();
  });
  await card.locator('[data-archive]').click(); await cancelled;
  assert.equal((await servers.state(teacherSession)).data.classroom.archived, false);
  await teacher.route('**/archive', route => route.abort());
  const accepted = teacher.waitForEvent('dialog').then(dialog => dialog.accept());
  await card.locator('[data-archive]').click(); await accepted;
  await expect(teacher.locator('#message')).toContainText('서버에 연결하지 못했습니다');
  assert.equal((await servers.state(teacherSession)).data.classroom.archived, false);
  await teacher.unroute('**/archive');
  await expect(card.locator('[data-archive]')).toBeEnabled({ timeout: 10000 });
  const confirmed = teacher.waitForEvent('dialog').then(dialog => dialog.accept());
  await card.locator('[data-archive]').click(); await confirmed;
  await expect(teacher.locator(`[data-manage="${teacherSession.classroomId}"]`)).toHaveCount(0);
  await teacher.locator('#archived-view').click();
  await expect(teacher.locator('#archived-view')).toHaveAttribute('aria-pressed', 'true');
  await expect(teacher.locator(`[data-manage="${teacherSession.classroomId}"]`)).toBeVisible();
  await expect(teacher.locator('#create')).toBeHidden();
  await teacher.reload();
  await expect(teacher.locator('#archived-view')).toHaveAttribute('aria-pressed', 'true');
  await teacher.locator(`[data-manage="${teacherSession.classroomId}"]`).click();
  await expect(teacher.locator('#enrollment-control')).toBeDisabled();
  await expect(teacher.locator('#enrollment-status')).toContainText('보관된 수업');
  await student.goto(servers.origin + '/lab3/');
  await expect(student.locator('#continue')).toBeEnabled(); await student.locator('#continue').click();
  await expect(student.locator('#activity')).toBeVisible();
  assert.equal((await servers.state(studentSession)).data.participant.cursor, 1);
  assert.equal((await servers.state(teacherSession)).data.participants.length, 1);
  await teacher.locator('#back-list').click();
  const restored = teacher.waitForEvent('dialog').then(dialog => {
    assert.ok(dialog.message().includes('종료 상태')); return dialog.accept();
  });
  await teacher.locator(`[data-archive="${teacherSession.classroomId}"]`).click(); await restored;
  await expect(teacher.locator(`[data-manage="${teacherSession.classroomId}"]`)).toHaveCount(0);
  await teacher.locator('#active-view').click();
  await expect(teacher.locator(`[data-manage="${teacherSession.classroomId}"]`)).toBeVisible();
  await teacher.locator(`[data-manage="${teacherSession.classroomId}"]`).click();
  await expect(teacher.locator('#enrollment-control')).toHaveText('수업 오픈');
  await expect(teacher.locator('#enrollment-control')).toBeEnabled();
  const state = (await servers.state(teacherSession)).data;
  assert.equal(state.classroom.enrollmentOpen, false); assert.equal(state.classroom.archived, false);
  assert.equal(state.participants.length, 1); assert.equal(state.participants[0].cursor, 1);
  await expect(teacher.locator('#admin-toolbar')).toBeVisible();
  assert.deepEqual(errors, []);
});
