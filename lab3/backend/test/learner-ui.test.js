import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { browserServers, MemoryStore } from './helpers.js';

test('compact learner layout, menu, activity gates, refresh chooser and explicit reset remain usable', { timeout: 90000 }, async t => {
  const servers = await browserServers(new MemoryStore()); t.after(() => servers.close());
  const browser = await chromium.launch({ channel: 'msedge', headless: true }); t.after(() => browser.close());
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const teacher = await servers.create();
  await page.goto(servers.origin + '/lab3/');
  assert.ok((await page.locator('#join').boundingBox()).y < 160);
  assert.ok((await page.locator('#join').boundingBox()).height < 400);
  await expect(page.locator('#restore, .recovery, #recovery-key')).toHaveCount(0);
  await page.locator('#join [name=code]').fill(teacher.classroomId);
  await page.locator('#join [name=nickname]').fill('간결한 화면');
  await page.locator('#join button').click();
  await expect(page.locator('#role')).toContainText('간결한 화면');
  const student = JSON.parse(await page.evaluate(origin => localStorage.getItem(`lab3.session:${origin}:student`), servers.apiOrigin));
  await servers.gate(teacher, '3-1', true);
  await expect(page.locator('#next-portion')).toBeVisible({ timeout: 10000 });
  await page.locator('#next-portion').click();
  await expect(page.locator('#activity')).toBeVisible();
  const frame = page.frameLocator('#activity');
  await expect(frame.locator('#clip-v')).toBeVisible();
  await expect(frame.locator('.lab-top')).toBeHidden();
  await expect(frame.locator('.addr')).toBeHidden();
  await expect(frame.locator('[data-clip=skip]')).toHaveCount(0);
  if (process.env.LAB3_UI_EVIDENCE_DIR) await mkdir(process.env.LAB3_UI_EVIDENCE_DIR, { recursive: true });
  for (const [width, height] of [[1440, 900], [1280, 800], [390, 844]]) {
    await page.setViewportSize({ width, height }); await page.evaluate(() => scrollTo(0, 0));
    const outer = await page.locator('#activity').boundingBox();
    assert.ok(outer.y <= 160, `Activity starts too low at ${width}: ${outer.y}`);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const inner = page.frames().find(item => item !== page.mainFrame());
    const dimensions = await inner.evaluate(() => {
      const guide = document.querySelector('#guide').getBoundingClientRect();
      const clip = document.querySelector('.clip-card').getBoundingClientRect();
      const controls = document.querySelector('.clip-ctl').getBoundingClientRect();
      return { overflow: document.documentElement.scrollWidth > innerWidth, guideRight: guide.right,
        width: innerWidth, clippedControls: controls.bottom > clip.bottom + 1 };
    });
    assert.equal(dimensions.overflow, false);
    assert.ok(dimensions.guideRight <= dimensions.width + 1);
    assert.equal(dimensions.clippedControls, false);
    if (width > 980) assert.ok(outer.height >= height * .75);
    if (process.env.LAB3_UI_EVIDENCE_DIR) await page.screenshot({ path: join(process.env.LAB3_UI_EVIDENCE_DIR, `local-working-${width}.png`) });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.locator('#learner-menu > summary').focus(); await page.keyboard.press('Enter');
  await expect(page.locator('#review')).toBeVisible();
  await expect(page.locator('#force-video')).toBeChecked();
  await page.locator('#force-video').uncheck();
  assert.equal(await page.evaluate(() => localStorage.getItem('lab3.force')), '0');
  await page.keyboard.press('Escape');
  await expect(page.locator('#review')).toBeHidden();
  const activity = page.frames().find(item => item !== page.mainFrame());
  await activity.evaluate(() => {
    watched = new Set(STEPS.map(step => step.id));
    document.querySelector('#clip-v').dispatchEvent(new Event('ended'));
  });
  await context.setOffline(true);
  await frame.locator('[data-g=next]').click();
  await expect(page.locator('#connection')).toBeVisible();
  await expect(page.locator('#connection')).toContainText('저장 대기');
  assert.equal((await servers.state(student)).data.participant.cursor, 0);
  await context.setOffline(false);
  await expect(frame.locator('[data-hot]')).toBeVisible({ timeout: 15000 });
  await frame.locator('[data-hot]').click();
  await frame.locator('[data-in]').fill('Contoso IT Concierge');
  const instructions = await activity.evaluate(() => LAB.steps.find(step => step.id === 'instructions').actions[0].value);
  await frame.locator('[data-in]').fill(instructions);
  await frame.locator('[data-q="0"]').click();
  await expect(frame.locator('.q-fb')).toContainText('다시 골라');
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await activity.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.ok(await frame.locator('.quiz').evaluate(element => element.getBoundingClientRect().width <= innerWidth));
  await page.setViewportSize({ width: 1440, height: 900 });
  await frame.locator('[data-q="2"]').click();
  await frame.locator('[data-g=qnext]').click();
  await expect(page.locator('#learner-status')).toContainText('강사 개방 대기');
  assert.equal((await servers.state(student)).data.participant.cursor, 5);
  await expect(frame.locator('#guide')).not.toContainText('다음 구간은');
  await servers.gate(teacher, '3-2', true);
  await expect(page.locator('#next-portion')).toBeVisible({ timeout: 10000 });
  await expect(page.locator('#next-portion')).toHaveText(/3-2/);
  await page.locator('#learner-menu > summary').click();
  await page.locator('#review').selectOption('3-1');
  await expect(page.locator('#learner-status')).toContainText('복습 · 3-1');
  assert.equal((await servers.state(student)).data.participant.cursor, 5);
  await page.locator('#learner-menu > summary').click(); await page.locator('#current').click();
  await expect(page.locator('#learner-status')).not.toContainText('복습');

  const stateUrl = `**/api/classrooms/${teacher.classroomId}`;
  await page.route(stateUrl, route => route.abort()); await page.reload();
  await expect(page.locator('#connection')).toBeVisible();
  await expect(page.locator('#join')).toBeHidden();
  await expect(page.locator('#continue')).toBeDisabled();
  await page.unroute(stateUrl);
  await expect(page.locator('#continue')).toBeEnabled({ timeout: 15000 });
  await page.locator('#continue').click();
  await expect(page.locator('#learner-status')).toContainText('완료');
  await expect(page.locator('#resume')).toBeHidden();
  await servers.gate(teacher, '3-1', false); await servers.gate(teacher, '3-2', false);
  await page.reload();
  await expect(page.locator('#resume')).toBeVisible();
  await expect(page.locator('#continue')).toBeEnabled();
  await page.locator('#restart').click();
  await expect(page.locator('#learner-status')).toContainText('실습 시작 대기');
  const reset = (await servers.state(student)).data.participant;
  assert.equal(reset.cursor, 0); assert.equal(reset.epoch, 1);
  assert.equal((await servers.state(teacher)).data.participants.length, 1);
  assert.equal((await servers.state(teacher)).data.classroom.portions[0].completedCount, 0);
  await expect(page.locator('#next-portion')).toBeHidden();
  await servers.gate(teacher, '3-1', true);
  await expect(page.locator('#next-portion')).toBeVisible({ timeout: 10000 });
  await page.locator('#next-portion').click();
  await expect(page.locator('#activity')).toBeVisible();
  await expect(frame.locator('[data-g=next]')).toBeVisible();
  await frame.locator('[data-g=next]').click();
  await expect(frame.locator('[data-hot]')).toBeVisible();
  assert.equal((await servers.state(student)).data.participant.cursor, 1);
  assert.deepEqual(errors, []);
});
